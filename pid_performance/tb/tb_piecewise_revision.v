function integer bcd_value(input [23:0] b);
 integer k,v,m;
 begin v=0;m=1;for(k=0;k<6;k=k+1)begin v=v+((b>>(k*4))&15)*m;m=m*10;end bcd_value=v;end
endfunction
task test_code(input integer code16,expected,expected_valid);
 integer i,c;
 begin
  @(negedge clk);rst_n=0;sample_valid=0;
  repeat(3) @(negedge clk);rst_n=1;
  for(i=0;i<16;i=i+1) begin
   c=code16/16+(i<(code16%16));
   @(negedge clk);pi_code=16383-c;sample_valid=1;
   @(negedge clk);sample_valid=0;
   repeat(5) @(negedge clk);
  end
  repeat(150) @(negedge clk);
  if(valid!==expected_valid || frame_valid!==expected_valid)
   $fatal(1,"FAIL validity code16=%d valid=%d",code16,valid);
  if(expected_valid) begin
   if($signed({1'b0,power})-expected>2 || expected-$signed({1'b0,power})>2)
    $fatal(1,"FAIL conversion code16=%d expect=%d got=%d",code16,expected,power);
   if(bcd_value(bcd)!=power) $fatal(1,"FAIL BCD vs reported power");
   for(i=0;i<60;i=i+1) begin
    @(negedge clk);
    if(sel!=63 && seg[7]!=(sel!=6'b101111)) $fatal(1,"FAIL decimal placement");
   end
  end
  tests=tests+1;
 end
endtask
